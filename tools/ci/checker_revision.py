#!/usr/bin/env python3
"""Regenerate the static checker's revision from the library's code.

    python tools/ci/checker_revision.py              # write include/jaiscript/detail/jaibite_checker_revision.hpp
    python tools/ci/checker_revision.py --check      # exit 1 when the committed file is not what the sources give
    python tools/ci/checker_revision.py --inputs     # the hashed files, one per line
    python tools/ci/checker_revision.py --selftest   # the hash's own checks, on a throwaway tree

A .jaibite's checked-clean stamp names the revision of the checker that gave it, and a load trusts it only under the same
revision (detail/ast_serializer.hpp). A rule that refuses a program can live anywhere the library is compiled from (the
checker, the parser, the engine, the class registry, a kernel header), so the revision is the first 24 bits of a SHA-256
over all of it: every C++ file under include/ and source/, source/tests excepted. That is the library, the interpreter,
the one-file build and the vendored code they compile; tools, examples and tests are programs that use the library.
Nobody bumps a number and nobody asks which file a rule is in.

Each file enters as its path from the package root and its code: comments read as one space, each run of white space
outside a literal as one space, CRLF as LF. A CRLF and an LF checkout, any platform, any build of one source and a copy
whose comments were rewritten agree, and a comment edit moves nothing. Paths go in byte order. Two branches that both
change the library's code conflict on the value's line; running this again on the merged sources settles it.
"""

import argparse
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
HASHED = ("include", "source")
NOT_HASHED = "source/tests/"
SUFFIXES = {".hpp", ".hh", ".hxx", ".h", ".inl", ".ipp", ".cpp", ".cc", ".cxx", ".c"}
OUTPUT = "include/jaiscript/detail/jaibite_checker_revision.hpp"
LF = b"\n"
CRLF = b"\r\n"

TEMPLATE = """#pragma once

#ifndef __JAISCRIPT_DETAIL_JAIBITE_CHECKER_REVISION_HPP__
#define __JAISCRIPT_DETAIL_JAIBITE_CHECKER_REVISION_HPP__

// Generated by tools/ci/checker_revision.py from the library's code; never edited by hand, and a conflict here is
// settled by running it again. Only source/implementation/jaibite_checker_revision.cpp includes it.
#include <cstdint>

namespace jai::detail {
    inline constexpr uint32_t k_jaibite_checker_revision = 0x{revision:06x};
}

#endif // __JAISCRIPT_DETAIL_JAIBITE_CHECKER_REVISION_HPP__
"""

OPENER = re.compile(r'//|/\*|R"|["\']')
RAW_STRING = re.compile(r'R"([^(\s\\]*)\(')
LITERAL_BODY = {'"': re.compile(r'(?:\\[\s\S]|[^"\\\n])*'), "'": re.compile(r"(?:\\[\s\S]|[^'\\\n])*")}
SPACE = re.compile(r"\s+")


def segments(text):
    """(kind, text) runs of a C++ source, kind in code, comment, literal."""
    result = []
    start = at = 0
    size = len(text)
    while True:
        opener = OPENER.search(text, at)
        if not opener:
            break
        begin = opener.start()
        token = opener.group()
        if token == "//":
            kind, end = "comment", text.find("\n", begin)
            end = size if end < 0 else end
        elif token == "/*":
            kind, end = "comment", text.find("*/", begin + 2)
            end = size if end < 0 else end + 2
        elif token == 'R"':
            raw = None if begin > 0 and (text[begin - 1].isalnum() or text[begin - 1] == "_") else RAW_STRING.match(text, begin)
            if not raw:
                at = begin + 1   # an identifier ending in R: its quote opens an ordinary literal
                continue
            kind, end = "literal", text.find(")" + raw.group(1) + '"', begin)
            end = size if end < 0 else end + len(raw.group(1)) + 2
        else:
            if token == "'" and begin > 0 and text[begin - 1].isalnum() and begin + 1 < size and text[begin + 1].isalnum():
                at = begin + 1   # a digit separator (1'000)
                continue
            kind, end = "literal", min(size, LITERAL_BODY[token].match(text, begin + 1).end() + 1)
        if begin > start:
            result.append(("code", text[start:begin]))
        result.append((kind, text[begin:end]))
        start = at = end
    if start < size:
        result.append(("code", text[start:]))
    return result


def code_of(data):
    """What a file is hashed as."""
    parts = []
    code = []
    for kind, text in segments(data.replace(CRLF, LF).decode("utf-8", errors="surrogateescape")):
        if kind == "comment":
            code.append(" ")
        elif kind == "code":
            code.append(text)
        else:
            parts.append(SPACE.sub(" ", "".join(code)))
            parts.append(text)
            code.clear()
    parts.append(SPACE.sub(" ", "".join(code)))
    return "".join(parts).strip().encode("utf-8", errors="surrogateescape")


def inputs(root):
    found = []
    for top in HASHED:
        for path in (root / top).rglob("*"):
            name = path.relative_to(root).as_posix()
            if path.suffix in SUFFIXES and not name.startswith(NOT_HASHED) and name != OUTPUT and path.is_file():
                found.append(name)
    return sorted(found, key=lambda name: name.encode("utf-8"))


def revision_of(root):
    digest = hashlib.sha256(b"jaibite checker revision" + LF)
    for name in inputs(root):
        code = code_of((root / name).read_bytes())
        digest.update(name.encode("utf-8") + b"\0" + str(len(code)).encode("ascii") + b"\0" + code)
    return int.from_bytes(digest.digest()[:3], "big")


def generated(revision):
    return TEMPLATE.replace("{revision:06x}", format(revision, "06x")).encode("utf-8")


def command():
    return "python " + pathlib.Path(__file__).resolve().as_posix()


def stale(root, revision):
    """Why the committed file is not the one this revision generates; None when it is."""
    output = root / OUTPUT
    have = output.read_bytes().replace(CRLF, LF) if output.is_file() else b""
    if have == generated(revision):
        return None
    said = re.search(rb"k_jaibite_checker_revision = (0x[0-9a-fA-F]+);", have)
    return (f"the checker revision is stale: {OUTPUT} {'says ' + said.group(1).decode('ascii') if said else 'is missing or edited'}, "
            f"the library's code gives 0x{revision:06x}. Run: {command()}")


def check(root):
    revision = revision_of(root)
    why = stale(root, revision)
    if why:
        print("::error::" + why)
        return 1
    print(f"checker revision: 0x{revision:06x}, as committed")
    return 0


def write(root):
    revision = revision_of(root)
    if not stale(root, revision):
        print(f"checker revision: 0x{revision:06x}, unchanged")
        return 0
    output = root / OUTPUT
    newline = CRLF if output.is_file() and CRLF in output.read_bytes() else LF
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(generated(revision).replace(LF, newline))
    print(f"checker revision: 0x{revision:06x}, written to {OUTPUT}")
    return 0


def selftest():
    import shutil
    import tempfile

    failed = []

    def expect(what, holds):
        print(("ok: " if holds else "FAIL: ") + what)
        if not holds:
            failed.append(what)

    sample = b'int a = 1; // one\n/* two */ char c = \'"\'; auto s = "// not a comment"; auto r = R"x(/* raw */)x";\n#define M 1\'000\n'
    kinds = [(kind, text) for kind, text in segments(sample.decode("utf-8")) if kind != "code"]
    expect("comments and literals split as C++ reads them",
           kinds == [("comment", "// one"), ("comment", "/* two */"), ("literal", "'\"'"), ("literal", '"// not a comment"'), ("literal", 'R"x(/* raw */)x"')])
    expect("a file hashes as its code, literals kept whole",
           code_of(sample) == b'int a = 1; char c = \'"\'; auto s = "// not a comment"; auto r = R"x(/* raw */)x"; #define M 1\'000')

    library = {
        "include/jaiscript/core/a.hpp": b"#pragma once\n// what a is\nint a(); /* soon */\n",
        "source/implementation/a.cpp": b'#include <jaiscript/core/a.hpp>\nstatic const char* text = "x y"; // a text\nint a() { return 1; }\n',
        "source/implementation/vm/b.cpp": b"int b() { return 2; }\n",
        "source/interpreter/c.cpp": b"int c() { return 3; }\n",
        "source/third_party/lib/d.h": b"int d(void);\n",
        "source/jaiscript.cpp": b'#include "implementation/a.cpp"\n',
    }
    beside = {
        "source/tests/t.cpp": b"int t() { return 4; }\n",
        "source/CMakeLists.txt": b"add_library(a)\n",
        "include/jaiscript/core/README.md": b"notes\n",
        OUTPUT: generated(1),
    }
    base = pathlib.Path(tempfile.mkdtemp(prefix="checker_revision_selftest_"))
    count = [0]

    def revision(files, newline=LF):
        count[0] += 1
        root = base / str(count[0])
        for name, data in files.items():
            (root / name).parent.mkdir(parents=True, exist_ok=True)
            (root / name).write_bytes(data.replace(LF, newline))
        return revision_of(root), root

    def changed(name, edit):
        files = {**library, **beside}
        files[name] = edit(files[name])
        return revision(files)[0]

    try:
        here, root = revision({**library, **beside})
        expect("the library's C++ files are the inputs: not the tests, a build file, a note or the generated file", inputs(root) == sorted(library))
        expect("the same code gives the same value in another tree", revision({**library, **beside})[0] == here)
        expect("a CRLF checkout gives the LF checkout's value", revision({**library, **beside}, CRLF)[0] == here)
        for name in library:
            expect(f"a comment and blank lines added to {name} keep the value", changed(name, lambda data: b"// a note\n\n" + data + b"\n/* the end */\n") == here)
            expect(f"a declaration added to {name} gives another value", changed(name, lambda data: data + b"int more;\n") != here)
        expect("white space changed inside a literal gives another value", changed("source/implementation/a.cpp", lambda data: data.replace(b'"x y"', b'"x  y"')) != here)
        expect("a change to a test or a build file keeps the value",
               changed("source/tests/t.cpp", lambda data: data + b"int more;\n") == here and changed("source/CMakeLists.txt", lambda data: data + b"more\n") == here)
        expect("a file added to the library gives another value", revision({**library, **beside, "source/implementation/e.cpp": b""})[0] != here)
        moved = {**library, **beside}
        moved["source/implementation/moved.cpp"] = moved.pop("source/implementation/a.cpp")
        expect("a file under another name gives another value", revision(moved)[0] != here)
        expect("the value in the tree is stale until written", stale(root, here) is not None and command() in stale(root, here))
        write(root)
        expect("a written value passes --check", stale(root, here) is None)
        (root / OUTPUT).write_bytes(generated(here ^ 1).replace(LF, CRLF))
        write(root)
        expect("a rewrite keeps the file's line endings", CRLF in (root / OUTPUT).read_bytes() and stale(root, here) is None)
        real = inputs(ROOT)
        expect("in this checkout the checker, the parser, the engine and the VM are inputs, the generated file and the tests are not",
               all("source/implementation/" + name in real for name in ("type_checker.cpp", "parser.cpp", "engine.cpp", "vm/vm_backend.cpp"))
               and OUTPUT not in real and not any(name.startswith(NOT_HASHED) for name in real))
    finally:
        shutil.rmtree(base, ignore_errors=True)
    print("SELFTEST RED" if failed else "SELFTEST GREEN")
    return 1 if failed else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--inputs", action="store_true")
    parser.add_argument("--selftest", action="store_true")
    arguments = parser.parse_args()
    if arguments.selftest:
        return selftest()
    if arguments.inputs:
        print("\n".join(inputs(ROOT)))
        return 0
    return check(ROOT) if arguments.check else write(ROOT)


if __name__ == "__main__":
    sys.exit(main())
