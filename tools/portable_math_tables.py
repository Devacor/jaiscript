#!/usr/bin/env python3
"""Writes source/implementation/portable_math_tables.hpp: the constants and tables of the portable math kernel
(source/implementation/portable_math.cpp). Every value is computed here from first principles in exact or 100-digit
arithmetic (the Python standard library only) and printed as a C++ hex float, so the kernel's data is reproducible.

    python tools/portable_math_tables.py          # rewrites the header
    python tools/portable_math_tables.py --check  # fails when the committed header differs
"""
import math
import sys
from decimal import Decimal, getcontext
from fractions import Fraction
from pathlib import Path

getcontext().prec = 110
OUT = Path(__file__).resolve().parent.parent / "source" / "implementation" / "portable_math_tables.hpp"


def atan_series(x):
    # x small: x - x^3/3 + x^5/5 - ...
    total, term, n, x2 = Decimal(0), x, 1, x * x
    while True:
        add = term / n
        if abs(add) < Decimal(10) ** -(getcontext().prec + 5):
            return total
        total += add if (n // 2) % 2 == 0 else -add
        term *= x2
        n += 2


def d_atan(x):
    # two halvings (atan x = 2 atan(x / (1 + sqrt(1 + x^2)))) put the argument under 0.21 for x <= 1
    if x < 0:
        return -d_atan(-x)
    if x > 1:
        return D_PI / 2 - d_atan(1 / x)
    y = x
    for _ in range(3):
        y = y / (1 + (1 + y * y).sqrt())
    return 8 * atan_series(y)


def d_sin(x):
    total, term, n = Decimal(0), x, 1
    while abs(term) > Decimal(10) ** -(getcontext().prec + 5):
        total += term
        term = -term * x * x / ((n + 1) * (n + 2))
        n += 2
    return total


def d_cos(x):
    total, term, n = Decimal(0), Decimal(1), 0
    while abs(term) > Decimal(10) ** -(getcontext().prec + 5):
        total += term
        term = -term * x * x / ((n + 1) * (n + 2))
        n += 2
    return total


D_PI = 16 * atan_series(Decimal(1) / 5) - 4 * atan_series(Decimal(1) / 239)
D_LN2 = Decimal(2).ln()
D_LN10 = Decimal(10).ln()


def frac(d):
    return d if isinstance(d, Fraction) else Fraction(d)


def dbl(v):
    return float(frac(v))


def dd(v):
    v = frac(v)
    hi = float(v)
    lo = float(v - Fraction(hi))
    return hi, lo


def bits_rounded(v, n):
    """v rounded to n significant bits (nearest)."""
    v = frac(v)
    if v == 0:
        return 0.0
    e = abs(v).numerator.bit_length() - abs(v).denominator.bit_length()
    while Fraction(2) ** e > abs(v):
        e -= 1
    while Fraction(2) ** (e + 1) <= abs(v):
        e += 1
    scale = Fraction(2) ** (n - 1 - e)
    result = Fraction(round(v * scale)) / scale
    assert float(result) == result
    return float(result)


def hexf(x):
    return x.hex() if x != 0 else ("-0x0.0p+0" if str(x).startswith("-") else "0x0.0p+0")


def two_over_pi_words(count):
    """2/pi's fraction bits, 32 a word, most significant first: integer arithmetic only (Machin's formula)."""
    bits = count * 32 + 64
    one = 1 << (bits + 64)

    def atan_inv(n):
        total, term, k, sign = 0, one // n, 1, 1
        while term:
            total += sign * (term // k)
            term //= n * n
            k += 2
            sign = -sign
        return total

    pi_fixed = 16 * atan_inv(5) - 4 * atan_inv(239)          # pi * 2^(bits + 64)
    two_over_pi = (2 * one * one) // pi_fixed                # 2/pi * 2^(bits + 64)
    two_over_pi >>= 64 + (bits - count * 32)                 # count * 32 fraction bits
    return [(two_over_pi >> (32 * (count - 1 - i))) & 0xFFFFFFFF for i in range(count)]


def main():
    lines = []
    put = lines.append
    put("#pragma once")
    put("")
    put("// Generated by tools/portable_math_tables.py; edit the generator, not this file.")
    put("")
    put("#include <cstdint>")
    put("")
    put("namespace jai::detail::portable_math_tables {")
    put("")

    def const(name, value):
        put(f"\tinline constexpr double {name} = {hexf(value)};   // {value!r}")

    pi = frac(D_PI)
    pio2 = pi / 2
    ln2 = frac(D_LN2)
    ln10 = frac(D_LN10)

    # trig argument reduction
    const("TWO_OVER_PI", dbl(2 / pi))
    p1 = bits_rounded(pio2, 33)
    const("PIO2_1", p1)
    const("PIO2_1T", dbl(pio2 - Fraction(p1)))
    p2 = bits_rounded(pio2 - Fraction(p1), 33)
    const("PIO2_2", p2)
    const("PIO2_2T", dbl(pio2 - Fraction(p1) - Fraction(p2)))
    # n = round(x 256/pi) for |x| < 2^14: |n| < 2^21, so n times the 32-bit part is exact
    const("INV_PI_256", dbl(256 / pi))
    q1 = bits_rounded(pi / 256, 32)
    const("PI_256_1", q1)
    const("PI_256_1T", dbl(pi / 256 - Fraction(q1)))
    hi, lo = dd(pio2)
    const("PIO2_HI", hi)
    const("PIO2_LO", lo)
    hi, lo = dd(pi)
    const("PI_HI", hi)
    const("PI_LO", lo)
    hi, lo = dd(pi / 4)
    const("PIO4_HI", hi)
    const("PIO4_LO", lo)
    hi, lo = dd(3 * pi / 4)
    const("THREE_PIO4_HI", hi)
    const("THREE_PIO4_LO", lo)

    # exp: k = round(x * 128 / ln2), r = x - k ln2/128 (|k| < 2^18, so k * LN2_128_HI is exact with 35 bits)
    const("INV_LN2_128", dbl(128 / ln2))
    l2h = bits_rounded(ln2 / 128, 35)
    const("LN2_128_HI", l2h)
    const("LN2_128_LO", dbl(ln2 / 128 - Fraction(l2h)))
    const("LN2", dbl(ln2))
    # log: e * LN2_HI exact for |e| <= 1075 (42 bits)
    l2 = bits_rounded(ln2, 42)
    const("LN2_HI", l2)
    const("LN2_LO", dbl(ln2 - Fraction(l2)))
    hi, lo = dd(1 / ln2)
    const("INV_LN2_HI", hi)
    const("INV_LN2_LO", lo)
    hi, lo = dd(1 / ln10)
    const("INV_LN10_HI", hi)
    const("INV_LN10_LO", lo)
    # 1/ln2 and 1/ln10 as a 26-bit part and the rest: a 26-bit factor times the 26-bit part is exact
    h = bits_rounded(1 / ln2, 26)
    const("INV_LN2_26", h)
    const("INV_LN2_26T", dbl(1 / ln2 - Fraction(h)))
    h = bits_rounded(1 / ln10, 26)
    const("INV_LN10_26", h)
    const("INV_LN10_26T", dbl(1 / ln10 - Fraction(h)))
    log10_2 = ln2 / ln10
    l102 = bits_rounded(log10_2, 42)
    const("LOG10_2_HI", l102)
    const("LOG10_2_LO", dbl(log10_2 - Fraction(l102)))
    put("")

    # Taylor coefficients, each the nearest double to the rational

    def series(name, values, note):
        put(f"\t// {note}")
        put(f"\tinline constexpr double {name}[{len(values)}] = {{" + ", ".join(hexf(dbl(v)) for v in values) + "};")

    series("SIN_TAYLOR", [Fraction((-1) ** n, math.factorial(2 * n + 1)) for n in range(1, 6)], "sin: x^3 .. x^11")
    series("COS_TAYLOR", [Fraction((-1) ** n, math.factorial(2 * n)) for n in range(2, 6)], "cos: x^4 .. x^10")
    series("EXP_TAYLOR", [Fraction(1, math.factorial(n)) for n in range(2, 7)], "exp: x^2 .. x^6")
    series("ATAN_TAYLOR", [Fraction((-1) ** n, 2 * n + 1) for n in range(1, 8)], "atan: x^3 .. x^15")
    series("LOG1P_TAYLOR", [Fraction((-1) ** (n + 1), n) for n in range(2, 10)], "log1p: x^2 .. x^9")
    # tan's Taylor coefficients: the series of sin over the series of cos, in exact rationals
    sin_c = [Fraction((-1) ** k, math.factorial(2 * k + 1)) for k in range(9)]
    cos_c = [Fraction((-1) ** k, math.factorial(2 * k)) for k in range(9)]
    tan_c = []
    for k in range(9):
        tan_c.append(sin_c[k] - sum(tan_c[i] * cos_c[k - i] for i in range(k)))
    series("TAN_TAYLOR", tan_c[1:8], "tan: x^3 .. x^15")
    series("CBRT_CORRECTION", [Fraction(1, 3), Fraction(-1, 9), Fraction(5, 81), Fraction(-10, 243)],
           "(1 + d)^(1/3) - 1: d .. d^4")
    put("")

    # 2^(j/128), j = 0..127, as hi + lo
    put("\t// 2^(j/128): hi, lo")
    put("\tinline constexpr double EXP2_128[128][2] = {")
    for j in range(128):
        hi, lo = dd(frac((Decimal(j) / 128 * D_LN2).exp()))
        put(f"\t\t{{{hexf(hi)}, {hexf(lo)}}},")
    put("\t};")
    put("")

    # log: m in [sqrt(1/2), sqrt(2)), 257 intervals; c ~ 1/m with 16 bits (c = 1 beside 1.0), -log(c) as hi + lo
    put("\t// log's intervals of m in [sqrt(1/2), sqrt(2)): index (m >= 1 ? 150 + top 8 mantissa bits : top 8 mantissa bits - 106);")
    put("\t// c (16 significant bits, 1 on the two intervals beside 1), then -log(c), -log2(c) and -log10(c), each hi, lo")
    put("\tinline constexpr double LOG_TABLE[257][7] = {")
    sqrt2 = Fraction(Decimal(2).sqrt())
    worst_r = Fraction(0)
    for idx in range(257):
        if idx < 150:
            t = idx + 106
            a, b = Fraction(1, 2) + Fraction(t, 512), Fraction(1, 2) + Fraction(t + 1, 512)
            a = max(a, 1 / sqrt2)
        else:
            t = idx - 150
            a, b = 1 + Fraction(t, 256), 1 + Fraction(t + 1, 256)
            b = min(b, sqrt2)
        if idx in (149, 150):
            c = 1.0
        else:
            c = bits_rounded(2 / (a + b), 16)
        for m in (a, b):
            worst_r = max(worst_r, abs(m * Fraction(c) - 1))
        ln_c = Decimal(c).ln()
        cols = [hexf(c)]
        for v in (-ln_c, -ln_c / D_LN2, -ln_c / D_LN10):
            hi, lo = dd(frac(v)) if c != 1.0 else (0.0, 0.0)
            cols += [hexf(hi), hexf(lo)]
        put("\t\t{" + ", ".join(cols) + "},")
    put("\t};")
    put(f"\t// the largest |m c - 1| over the intervals: {float(worst_r)!r}")
    put("")

    # sin and cos at j/128, j = 0..102
    put("\t// sin(j/128) and cos(j/128): sin hi, sin lo, cos hi, cos lo")
    put("\tinline constexpr double SINCOS_128[103][4] = {")
    for j in range(103):
        a = Decimal(j) / 128
        s_hi, s_lo = dd(frac(d_sin(a)))
        c_hi, c_lo = dd(frac(d_cos(a)))
        put(f"\t\t{{{hexf(s_hi)}, {hexf(s_lo)}, {hexf(c_hi)}, {hexf(c_lo)}}},")
    put("\t};")
    put("")

    # sin and cos at j pi/256, j = 0..64
    put("\t// sin(j pi/256) and cos(j pi/256) for j = -64..64: sin hi, sin lo, cos hi, cos lo")
    put("\tinline constexpr double SINCOS_PI_256[129][4] = {")
    for j in range(-64, 65):
        a = D_PI * j / 256
        s_hi, s_lo = dd(frac(d_sin(a)))
        c_hi, c_lo = dd(frac(d_cos(a)))
        put(f"\t\t{{{hexf(s_hi)}, {hexf(s_lo)}, {hexf(c_hi)}, {hexf(c_lo)}}},")
    put("\t};")
    put("")

    # tan at m pi/256, m = 0..120, with 1 + tan^2
    put("\t// tan(m pi/256): hi, lo, and 1 + tan^2 rounded")
    put("\tinline constexpr double TAN_PI_256[121][3] = {")
    for m in range(121):
        a = D_PI * m / 256
        t = d_sin(a) / d_cos(a)
        t_hi, t_lo = dd(frac(t))
        put(f"\t\t{{{hexf(t_hi)}, {hexf(t_lo)}, {hexf(dbl(frac(1 + t * t)))}}},")
    put("\t};")
    put("")

    # atan at j/256, j = 0..256
    put("\t// atan(j/256): hi, lo")
    put("\tinline constexpr double ATAN_256[257][2] = {")
    for j in range(257):
        hi, lo = dd(frac(d_atan(Decimal(j) / 256)))
        put(f"\t\t{{{hexf(hi)}, {hexf(lo)}}},")
    put("\t};")
    put("")

    # 2/pi's bits for the large-argument reduction, two zero words first (the window may start before the binary point)
    words = two_over_pi_words(42)
    put("\t// 2/pi's fraction bits, 32 a word from the most significant, after two zero words")
    put("\tinline constexpr std::uint32_t TWO_OVER_PI_BITS[44] = {")
    row = ["0x00000000u", "0x00000000u"] + [f"0x{w:08X}u" for w in words]
    for i in range(0, len(row), 8):
        put("\t\t" + ", ".join(row[i:i + 8]) + ",")
    put("\t};")
    put("")

    # cbrt's first guess on [1, 2): Chebyshev interpolation, degree 5
    deg = 5
    nodes = [1.5 + 0.5 * math.cos(math.pi * (k + 0.5) / (deg + 1)) for k in range(deg + 1)]
    # solve the Vandermonde system in exact fractions on rounded nodes
    xs = [Fraction(n) for n in nodes]
    ys = [frac(Decimal(n) ** (Decimal(1) / 3)) for n in nodes]
    mat = [[x ** p for p in range(deg + 1)] + [y] for x, y in zip(xs, ys)]
    for col in range(deg + 1):
        piv = max(range(col, deg + 1), key=lambda r: abs(mat[r][col]))
        mat[col], mat[piv] = mat[piv], mat[col]
        for r in range(deg + 1):
            if r != col:
                f = mat[r][col] / mat[col][col]
                mat[r] = [u - f * v for u, v in zip(mat[r], mat[col])]
    coeffs = [float(mat[r][deg + 1] / mat[r][r]) for r in range(deg + 1)]
    worst = 0.0
    for k in range(2001):
        m = 1 + k / 2000
        p = 0.0
        for cc in reversed(coeffs):
            p = p * m + cc
        worst = max(worst, abs(p / m ** (1 / 3) - 1))
    put(f"\t// cbrt(m) on [1, 2), relative error {worst:.3g}: c0 + m (c1 + m (c2 + m (c3 + m (c4 + m c5))))")
    put("\tinline constexpr double CBRT_GUESS[6] = {" + ", ".join(hexf(c) for c in coeffs) + "};")
    hi = [dbl(frac(Decimal(2) ** (Decimal(i) / 3))) for i in range(3)]
    put("\tinline constexpr double CBRT_2_I[3] = {" + ", ".join(hexf(c) for c in hi) + "};")
    put("")

    # asin(s) = s + s z (1/6 + z P(z)/Q(z)), z = s^2 <= 1/4: P/Q (degrees 4 and 4, Q's constant 1) interpolates
    # g(z) = ((asin(s) - s) / (s z) - 1/6) / z at 9 Chebyshev nodes, solved in exact rationals
    def asin_g(z):
        sq = z.sqrt()
        return ((d_atan(sq / (1 - z).sqrt()) - sq) / (sq * z) - Decimal(1) / 6) / z

    deg_p, deg_q = 4, 4
    count = deg_p + deg_q + 1
    nodes = [Fraction(0.125 + 0.125 * math.cos(math.pi * (k + 0.5) / count)) for k in range(count)]
    rows = []
    for z in nodes:
        gz = frac(asin_g(Decimal(z.numerator) / Decimal(z.denominator)))
        rows.append([z ** k for k in range(deg_p + 1)] + [-gz * z ** k for k in range(1, deg_q + 1)] + [gz])
    for col in range(count):
        piv = max(range(col, count), key=lambda r: abs(rows[r][col]))
        rows[col], rows[piv] = rows[piv], rows[col]
        for r in range(count):
            if r != col and rows[r][col] != 0:
                f = rows[r][col] / rows[col][col]
                rows[r] = [u - f * v for u, v in zip(rows[r], rows[col])]
    solution = [rows[r][count] / rows[r][r] for r in range(count)]
    asin_p = [dbl(v) for v in solution[:deg_p + 1]]
    asin_q = [dbl(v) for v in solution[deg_p + 1:]]
    worst = Fraction(0)
    for k in range(1, 201):
        z = Fraction(k, 800)
        pv = sum(Fraction(c) * z ** i for i, c in enumerate(asin_p))
        qv = 1 + sum(Fraction(c) * z ** (i + 1) for i, c in enumerate(asin_q))
        worst = max(worst, abs(pv / qv - frac(asin_g(Decimal(z.numerator) / Decimal(z.denominator)))))
    put(f"\t// asin's z P(z)/Q(z) term on [0, 1/4], absolute error {float(worst):.3g}: P's z^0 .. z^4, Q's z^1 .. z^4")
    put("\tinline constexpr double ASIN_P[5] = {" + ", ".join(hexf(c) for c in asin_p) + "};")
    put("\tinline constexpr double ASIN_Q[4] = {" + ", ".join(hexf(c) for c in asin_q) + "};")
    put(f"\tinline constexpr double SIXTH = {hexf(dbl(Fraction(1, 6)))};")
    put("")
    put("} // namespace jai::detail::portable_math_tables")
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is not what tools/portable_math_tables.py writes")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
